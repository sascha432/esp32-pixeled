uint16_t text_width(const char *text)
{
    uint32_t width = 0;
    bool any = false;
    for (uint16_t code = next(text); code != 0; code = next(text)) {
        uint8_t first = 0, w = 0;
        extent(glyph(code), code, first, w);
        width += w + (any ? 1u : 0u);
        any = true;
    }
    return static_cast<uint16_t>(width > 0xffff ? 0xffff : width);
}

void draw_text(Canvas &canvas, const char *text, int x, int y, Rgb color)
{
    bool any = false;
    for (uint16_t code = next(text); code != 0; code = next(text)) {
        const uint8_t *columns = glyph(code);
        uint8_t first = 0, w = 0;
        extent(columns, code, first, w);
        x += any ? 1 : 0;
        any = true;
        if (x >= canvas.width) {
            return;
        }
        for (uint8_t c = 0; c < w && code != ' '; c++) {
            column(canvas, columns[first + c], kTextHeight, x + c, y, color);
        }
        x += w;
    }
}

int text_x(uint16_t canvas_width, uint16_t width, uint8_t speed, uint32_t ms)
{
    if (width <= canvas_width) {
        return (canvas_width - width) / 2;
    }
    if (speed == 0) {
        return 0;
    }
    // in from the right edge, out at the left, then again
    const uint32_t pixels_per_s = 5u + speed * 45u / 255u;
    const uint32_t way = static_cast<uint32_t>(canvas_width) + width;
    const auto moved = static_cast<uint32_t>(static_cast<uint64_t>(ms) * pixels_per_s / 1000u % way);
    return static_cast<int>(canvas_width) - static_cast<int>(moved);
}

void draw_clock(Canvas &canvas, uint8_t hours, uint8_t minutes, bool colon, Rgb color)
{
    const uint8_t digits[4] = {static_cast<uint8_t>(hours / 10 % 10), static_cast<uint8_t>(hours % 10),
                               static_cast<uint8_t>(minutes / 10 % 10), static_cast<uint8_t>(minutes % 10)};
    // the large font: four digits 5 wide, the colon 2, a pixel between them
    const int large = 4 * 5 + 2 + 4;
    if (large <= canvas.width && kTextHeight <= canvas.height) {
        int x = (canvas.width - large) / 2;
        const int y = (canvas.height - kTextHeight) / 2;
        for (size_t i = 0; i < 4; i++) {
            const uint8_t *columns = kFont['0' + digits[i] - 0x20];
            for (int c = 0; c < 5; c++) {
                column(canvas, columns[c], kTextHeight, x + c, y, color);
            }
            x += 6;
            if (i == 1) {
                column(canvas, colon ? 0x36 : 0, kTextHeight, x, y, color);
                column(canvas, colon ? 0x36 : 0, kTextHeight, x + 1, y, color);
                x += 3;
            }
        }
        return;
    }
    // 3 x 5: four digits, the colon 1, a pixel between them
    const int small = 4 * 3 + 1 + 4;
    int x = (canvas.width - small) / 2;
    const int y = (canvas.height - 5) / 2;
    for (size_t i = 0; i < 4; i++) {
        for (int c = 0; c < 3; c++) {
            column(canvas, kSmallDigits[digits[i]][c], 5, x + c, y, color);
        }
        x += 4;
        if (i == 1) {
            column(canvas, colon ? 0x0a : 0, 5, x, y, color);
            x += 2;
        }
    }
}

