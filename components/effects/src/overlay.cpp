constexpr uint8_t kUnknown[5] = {0x02, 0x01, 0x51, 0x09, 0x06}; // ?

// 3 x 5 digits for the clock on a small canvas, bit 0 the top row
constexpr uint8_t kSmallDigits[10][3] = {
    {0x1f, 0x11, 0x1f}, {0x12, 0x1f, 0x10}, {0x1d, 0x15, 0x17}, {0x15, 0x15, 0x1f}, {0x07, 0x04, 0x1f},
    {0x17, 0x15, 0x1d}, {0x1f, 0x15, 0x1d}, {0x01, 0x01, 0x1f}, {0x1f, 0x15, 0x1f}, {0x17, 0x15, 0x1f},
};

// The next character of a UTF-8 text, and the text moved on; 0 at the end. A broken sequence is
// one unknown character.
uint16_t next(const char *&text)
{
    const auto c = static_cast<uint8_t>(*text);
    if (c == 0) {
        return 0;
    }
    text++;
    if (c < 0x80) {
        return c;
    }
    const auto c2 = static_cast<uint8_t>(*text);
    if ((c & 0xe0) == 0xc0 && (c2 & 0xc0) == 0x80) {
        text++;
        return static_cast<uint16_t>((c & 0x1f) << 6 | (c2 & 0x3f));
    }
    // longer sequences: skip their continuation bytes
    while ((static_cast<uint8_t>(*text) & 0xc0) == 0x80) {
        text++;
    }
    return 0xffff;
}

const uint8_t *glyph(uint16_t code)
{
    if (code >= 0x20 && code < 0x7f) {
        return kFont[code - 0x20];
    }
    for (const Extra &e : kExtras) {
        if (e.code == code) {
            return e.columns;
        }
    }
    return kUnknown;
}

// the columns a glyph shows: without the empty ones at its sides; a space is 3 wide
void extent(const uint8_t *columns, uint16_t code, uint8_t &first, uint8_t &width)
{
    if (code == ' ') {
        first = 0;
        width = 3;
        return;
    }
    first = 0;
    while (first < 5 && columns[first] == 0) {
        first++;
    }
    uint8_t last = 5;
    while (last > first && columns[last - 1] == 0) {
        last--;
    }
    width = static_cast<uint8_t>(last - first);
}

void plot(Canvas &canvas, int x, int y, Rgb color)
{
    if (x >= 0 && y >= 0 && x < canvas.width && y < canvas.height) {
        canvas.at(static_cast<uint16_t>(x), static_cast<uint16_t>(y)) = color;
    }
}

// one column of `rows` bits at x, y
void column(Canvas &canvas, uint8_t bits, int rows, int x, int y, Rgb color)
{
    for (int row = 0; row < rows; row++) {
        if ((bits >> row & 1) != 0) {
            plot(canvas, x, y + row, color);
        }
    }
}

